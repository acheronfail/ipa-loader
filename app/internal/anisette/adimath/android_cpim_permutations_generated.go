// BuildAndroidCPIMByteBanks builds the eight permutation banks used by the
// Android session cipher. seed is TransformAndroidSPIMBody(...)[176:240].
func BuildAndroidCPIMByteBanks(seed [64]byte) (banks [8][256]byte) {
	var words [16]uint32
	for i := range words {
		for k := 0; k < 4; k++ {
			words[i] |= uint32(seed[4*i+k]) << (8 * k)
		}
	}
	for i := uint32(0); i < 256; i++ {
		values, indices := androidPermutationElement(words, i)
		for k := range banks {
			banks[k][indices[k]] = values[k]
		}
	}
	return
}
